#!/usr/bin/env python3
"""No old name survives in the documentation, the examples or the editor data.

With ninety renames, looking for them by eye does not work: this script reads the table from the
catalog itself - StdLib for the core.* modules, BlossomApi for core.mc.* - and looks for the names
that no longer exist. The migration tables at the bottom of the pages are the only place where an
old name belongs, and they are skipped.

    python3 tools/check-old-names.py
"""
import re
import sys
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

# the sections that list the old names on purpose
SKIP_FROM = re.compile(r'^##+ .*Coming from', re.M)


def catalog_pairs(source: str):
    """The (public name, implementation) pairs declared in a catalog."""
    pairs = []
    for body in re.findall(r'java\.util\.Map\.(?:ofEntries|of)\((.*?)\);', source, re.S):
        pairs += re.findall(r'"([^"]+)"\s*,\s*"([^"]+)"', body)
    return pairs


def plain_symbols(source: str):
    """The symbols declared without a map: the prelude, and the modules that renamed nothing."""
    names = set()
    for body in re.findall(r'Set\.of\((.*?)\);', source, re.S):
        names |= set(re.findall(r'"([^"]+)"', body))
    for body in re.findall(r'module\("[\w.]+",\s*\n?((?:\s*"[^"]+",?\s*)+)\);', source, re.S):
        names |= set(re.findall(r'"([^"]+)"', body))
    return names


def old_names():
    sources = [
        ROOT / 'blossom-core/src/main/java/blossom/language/StdLib.java',
        ROOT / 'blossom/src/main/java/com/gnottero/blossom/BlossomApi.java',
    ]
    public, implementation = set(), set()
    for path in sources:
        source = path.read_text(encoding='utf-8')
        for name, impl in catalog_pairs(source):
            public.add(name)
            implementation.add(impl)
        # the prelude and the modules that renamed nothing are still declared as a list
        public |= plain_symbols(source)
    # a name that was only an implementation and is no longer a public name is an old name
    return sorted(implementation - public)


def files():
    for folder in ('docs', 'examples', 'vscode-blossom/data'):
        for path in (ROOT / folder).rglob('*'):
            if path.name == 'api.json':
                continue    # generated by tools/generate-api.js: it also carries the implementation
                            # names, which are internal details rather than old names
            if path.is_file() and path.suffix in ('.md', '.bs', '.bsl', '.json'):
                yield path
    yield ROOT / 'README.md'


def main():
    names = old_names()
    if not names:
        print('no rename declared in the catalogs')
        return 0
    found = []
    for path in files():
        text = path.read_text(encoding='utf-8')
        match = SKIP_FROM.search(text)
        if match:
            text = text[:match.start()]
        for name in names:
            # only where the name really is a symbol: a call 'name(' or a qualified access
            # 'alias.name'. Without this, words like 'task' or 'print' would be found in every
            # line of prose that mentions them
            pattern = rf'(?:(?<=\.)|(?<![\w.])){re.escape(name)}(?=\()|(?<=\.){re.escape(name)}(?![\w])'
            for hit in re.finditer(pattern, text):
                # 'core.task' is the name of a module, not a use of the symbol 'task'
                before = text[max(0, hit.start() - 8):hit.start()]
                if before.endswith('core.') or before.endswith('mc.'):
                    continue
                line = text.count('\n', 0, hit.start()) + 1
                found.append(f'{path.relative_to(ROOT)}:{line}: {name}')
    if found:
        print(f'{len(found)} old names still around:')
        for line in found:
            print('  ' + line)
        return 1
    print(f'none of the {len(names)} old names survives')
    return 0


if __name__ == '__main__':
    sys.exit(main())
