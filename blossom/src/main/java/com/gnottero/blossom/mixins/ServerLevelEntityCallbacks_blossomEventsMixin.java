package com.gnottero.blossom.mixins;

import org.spongepowered.asm.mixin.Final;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.entity.Entity;

import com.gnottero.blossom.event.Event;
import com.gnottero.blossom.event.Fire;

/**
 * Fires {@code entity_loads}: an entity appeared in the world.
 *
 * <p>The hook is {@code onCreated}, the point where the entity enters the level memory. It covers
 * all three ways one appears, read back from disk with its chunk, generated by the world, or
 * summoned by someone, and they are the same thing to a listener: the entity was not there and now
 * it is.
 *
 * <p>Not {@code onTrackingStart}, which would look like the natural candidate: that fires when the
 * entity becomes visible to someone, so on a server with no players nearby it never fires. Verified
 * in game: with {@code onTrackingStart} a summoned entity fired no event at all.
 */
@Mixin(targets = "net.minecraft.server.level.ServerLevel$EntityCallbacks")
public abstract class ServerLevelEntityCallbacks_blossomEventsMixin
{
    @Shadow
    @Final
    ServerLevel this$0;

    @Inject(method = "onCreated(Lnet/minecraft/world/entity/Entity;)V", at = @At("TAIL"), require = 1)
    private void blossom$onEntityLoads(Entity entity, CallbackInfo ci)
    {
        if (Event.ENTITY_LOADS.isListened())
        {
            Fire.entityLoads(this$0, entity);
        }
    }
}
